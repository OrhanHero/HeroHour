"""Generate UV crops from existing original PNG alpha, without modifying images.

Blender metadata bounds are inclusive and bottom-left, whereas Unreal canvas
UVs and Pillow pixels are top-left. Validate that conversion against PNG alpha.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'Art/UI/PortraitsV5'
HEADER = ROOT / 'Source/HeroHourPrototype/PrototypePortraitBounds.h'
MANIFEST = ROOT / 'docs/verification/2026-10-16/tempest-ui/portrait-bounds.json'
PAD = 6


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    metadata = SOURCE / 'metadata.json'
    digest = sha(metadata)
    records = json.loads(metadata.read_text(encoding='utf-8'))['records']
    assert len(records) == 22
    result = []
    for entry in sorted(records, key=lambda row: row['file']):
        path = SOURCE / entry['file']
        before = sha(path)
        with Image.open(path) as image:
            assert image.mode == 'RGBA', (path, image.mode)
            width, height = image.size
            assert (width, height) == (512, 512)
            # Same > .01 occupancy rule as render_reference_portraits_v7.py.
            occupied = image.getchannel('A').point(lambda value: 255 if value >= 3 else 0)
            bounds = occupied.getbbox()
            assert bounds is not None
        metadata_bounds = entry.get('alpha_bounds')
        converted = None
        if metadata_bounds is not None:
            x0, y0, x1, y1 = metadata_bounds
            converted = (x0, height - 1 - y1, x1 + 1, height - y0)
            # Alpha quantization can move a single edge by one pixel.
            assert all(abs(a - b) <= 1 for a, b in zip(converted, bounds)), (path, converted, bounds)
        x0, y0, x1, y1 = bounds
        padded = [max(0, x0 - PAD), max(0, y0 - PAD), min(width, x1 + PAD), min(height, y1 + PAD)]
        uv = [padded[0] / width, padded[1] / height, padded[2] / width, padded[3] / height]
        aspect = (padded[2] - padded[0]) / (padded[3] - padded[1])
        assert sha(path) == before
        result.append({'texture': path.stem, 'sha256': before,
                       'metadata_bottom_left_inclusive': metadata_bounds,
                       'metadata_converted_top_left_exclusive': converted,
                       'verified_png_alpha_bounds_top_left_exclusive': list(bounds),
                       'padded_bounds': padded, 'uv_u0_v0_u1_v1': uv, 'aspect': aspect})
    rows = [
        '#pragma once', '#include "CoreMinimal.h"', '',
        '// Generated by Scripts/ui/build_portrait_bounds.py; do not edit by hand.',
        f'// Source Art/UI/PortraitsV5/metadata.json SHA-256 {digest}',
        '// PNG hashes, original Blender bounds, verified top-left crops and aspects:',
        '// docs/verification/2026-10-16/tempest-ui/portrait-bounds.json',
        '// Six pixel alpha padding; UV returns U0,V0,U1,V1 (not width/height).',
        'struct FPrototypePortraitBounds', '{',
        '    FName Name;', '    FVector4f UV;', '    float Aspect;', '};', '',
        'inline const FPrototypePortraitBounds* FindPrototypePortraitBounds(FName TextureName)',
        '{', '    static const FPrototypePortraitBounds Bounds[] =', '    {'
    ]
    for record in result:
        values = ','.join(f'{value:.9f}f' for value in record['uv_u0_v0_u1_v1'])
        rows.append(f'        {{FName(TEXT("{record["texture"]}")), FVector4f({values}), {record["aspect"]:.9f}f}},')
    rows += ['    };', '    for (const auto& Entry : Bounds)',
             '        if (Entry.Name == TextureName) return &Entry;',
             '    return nullptr;', '}', '',
             'inline FVector4f PrototypePortraitUV(FName TextureName)', '{',
             '    if (const auto* Bounds = FindPrototypePortraitBounds(TextureName)) return Bounds->UV;',
             '    return FVector4f(0.f,0.f,1.f,1.f);', '}', '',
             'inline float PrototypePortraitAspect(FName TextureName)', '{',
             '    if (const auto* Bounds = FindPrototypePortraitBounds(TextureName)) return Bounds->Aspect;',
             '    return 1.f;', '}', '']
    HEADER.write_text('\n'.join(rows), encoding='utf-8')
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps({'generator': 'Scripts/ui/build_portrait_bounds.py',
                                  'metadata_sha256': digest, 'padding_pixels': PAD,
                                  'alpha_threshold_byte': 3,
                                  'header_sha256': sha(HEADER), 'records': result}, indent=2) + '\n', encoding='utf-8')
    assert sha(metadata) == digest
    print(f'PORTRAIT_UV_BOUNDS_PASS {len(result)} original PNGs unchanged; metadata {digest}')


if __name__ == '__main__':
    main()
