import unreal

world = unreal.EditorLevelLibrary.new_level('/Game/Maps/Prototype')
mesh = unreal.load_asset('/Engine/BasicShapes/Cube')
ground = unreal.EditorLevelLibrary.spawn_actor_from_class(unreal.StaticMeshActor, unreal.Vector(0, 0, -50))
ground.set_actor_label('Prototype Ground')
ground.static_mesh_component.set_static_mesh(mesh)
ground.set_actor_scale3d(unreal.Vector(60, 60, 1))
light = unreal.EditorLevelLibrary.spawn_actor_from_class(unreal.DirectionalLight, unreal.Vector(0, 0, 1000), unreal.Rotator(-45, -30, 0))
light.set_actor_label('Sun')
light.light_component.set_editor_property('mobility', unreal.ComponentMobility.MOVABLE)
light.light_component.set_editor_property('intensity', 5.0)
sky = unreal.EditorLevelLibrary.spawn_actor_from_class(unreal.SkyLight, unreal.Vector(0, 0, 500))
sky.light_component.set_editor_property('mobility', unreal.ComponentMobility.MOVABLE)
sky.light_component.set_editor_property('intensity', 1.0)
unreal.EditorLevelLibrary.set_level_viewport_camera_info(unreal.Vector(-1400, 0, 2000), unreal.Rotator(-55, 0, 0))
start = unreal.EditorLevelLibrary.spawn_actor_from_class(unreal.PlayerStart, unreal.Vector(-600, 0, 1600))
start.set_actor_label('RTS Camera Start')
unreal.EditorLevelLibrary.save_current_level()
unreal.log('HEROHOUR_BOOTSTRAP_MAP_CREATED')
